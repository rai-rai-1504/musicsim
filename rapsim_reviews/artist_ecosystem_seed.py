def _seed_from_spec(spec: tuple) -> EcosystemArtistSeed:
    # Specs can optionally include base overrides for genre/theme/skill profile construction.
    # Base layout (12 fields):
    # (name, role, genres, themes, skills, popularity, qc, tendency, friendliness, controversy, aggression, cost)
    # Optional tail (3 fields): (base_genre, base_theme, base_skill)
    if len(spec) not in (12, 15):
        raise ValueError(f"Bad seed spec length: {len(spec)} for {spec[0]}")
    (
        name,
        role,
        genre_overrides,
        theme_overrides,
        skill_overrides,
        popularity,
        qc,
        tendency,
        friendliness,
        controversy,
        aggression,
        cost,
        *tail,
    ) = spec
    base_genre = 18
    base_theme = 18
    base_skill = 20
    if tail:
        base_genre, base_theme, base_skill = tail
    return EcosystemArtistSeed(
        name=str(name),
        role=str(role),
        genres=genre_profile(dict(genre_overrides), base=int(base_genre)),
        themes=theme_profile(dict(theme_overrides), base=int(base_theme)),
        skills=skill_profile(dict(skill_overrides), base=int(base_skill)),
        popularity=float(popularity),
        quality_consistency=int(qc),
        release_tendency=int(tendency),
        friendliness=int(friendliness),
        controversy=int(controversy),
        aggression=int(aggression),
        feature_cost=int(cost),
    )


