@dataclass(frozen=True)
class EcosystemArtistSeed:
    name: str
    role: str
    genres: dict[str, int]
    themes: dict[str, int]
    skills: dict[str, int]
    popularity: float
    quality_consistency: int
    release_tendency: int
    friendliness: int
    controversy: int
    aggression: int
    feature_cost: int
    battle_skills: int = 50
    project_ability: int | None = None
    gender: str = "male"
    sexuality: str | None = None
    romance_preference: str | None = None


VALID_ROMANCE_PREFERENCES = ("prefers_male", "prefers_female", "prefers_both")


def _stable_seed_rng(label: str) -> random.Random:
    value = 0
    for ch in label:
        value = (value * 131 + ord(ch)) & 0xFFFFFFFF
    return random.Random(value)


def _hidden_romance_preference_for_name(name: str) -> str:
    rng = _stable_seed_rng("romance-pref:" + str(name))
    return rng.choices(
        VALID_ROMANCE_PREFERENCES,
        weights=[18, 74, 8],
        k=1,
    )[0]


def proficiencies(base: int, overrides: dict[str, int]) -> dict[str, int]:
    data = {key: base for key in GENRES + THEMES + SKILLS}
    data.update(overrides)
    return data


def genre_profile(overrides: dict[str, int], base: int = 18) -> dict[str, int]:
    return {genre: proficiencies(base, overrides)[genre] for genre in GENRES}


def theme_profile(overrides: dict[str, int], base: int = 18) -> dict[str, int]:
    return {theme: proficiencies(base, overrides)[theme] for theme in THEMES}


def skill_profile(overrides: dict[str, int], base: int = 20) -> dict[str, int]:
    return {skill: proficiencies(base, overrides)[skill] for skill in SKILLS}


